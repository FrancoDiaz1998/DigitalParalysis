CREATE TABLE public.usuario (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY,
    nombre text NOT NULL,
    apellido text NOT NULL,
    nombre_usuario text NOT NULL,
    email text NOT NULL,
    contrasena_hash text NOT NULL,
    foto text,
    fecha_nacimiento date NOT NULL,
    rol text NOT NULL DEFAULT 'usuario',
    id_estado integer NOT NULL DEFAULT 1,
    fecha_registro timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    fecha_fin_suspension timestamp with time zone,
    fecha_eliminacion timestamp with time zone,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT ck_usuario_apellido_longitud CHECK (char_length(apellido) >= 2),
    CONSTRAINT ck_usuario_nombre_longitud CHECK (char_length(nombre) >= 2),
    CONSTRAINT ck_usuario_nombre_usuario_longitud CHECK (char_length(nombre_usuario) >= 2),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('usuario', 'admin')),
    CONSTRAINT fk_usuario_estado FOREIGN KEY (id_estado) REFERENCES public.estado_usuario (id_estado)
);

CREATE TABLE public.obra (
    id_obra integer GENERATED BY DEFAULT AS IDENTITY,
    id_tipo integer NOT NULL,
    titulo text NOT NULL,
    anio integer NOT NULL,
    sinopsis text NOT NULL,
    duracion integer NOT NULL,
    foto text,
    datos_curiosos text,
    pais_origen text NOT NULL,
    CONSTRAINT pk_obra PRIMARY KEY (id_obra),
    CONSTRAINT ck_obra_anio CHECK (anio >= 1888),
    CONSTRAINT ck_obra_duracion CHECK (duracion > 0),
    CONSTRAINT ck_obra_titulo_longitud CHECK (char_length(titulo) >= 1),
    CONSTRAINT fk_obra_tipo FOREIGN KEY (id_tipo) REFERENCES public.tipo_obra (id_tipo)
);

CREATE TABLE public.articulo (

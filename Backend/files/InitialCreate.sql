    CONSTRAINT pk_articulo PRIMARY KEY (id_articulo),
    CONSTRAINT ck_articulo_contenido_longitud CHECK (char_length(contenido) >= 1),
    CONSTRAINT ck_articulo_titulo_longitud CHECK (char_length(titulo) >= 3),
    CONSTRAINT fk_articulo_usuario FOREIGN KEY (id_usuario) REFERENCES public.usuario (id_usuario)
);

